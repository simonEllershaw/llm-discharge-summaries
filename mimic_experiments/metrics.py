"""Compute and export evaluation metrics for LLM-generated MIMIC discharge summaries."""

import json
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

BASE_DIR = Path(__file__).resolve().parent
OUTPUT_DIR = BASE_DIR / "outputs"
ANNOTATED_DIR = OUTPUT_DIR / "annotators_eval"
METRICS_OUTPUT_DIR = OUTPUT_DIR / "metrics"

MISSED_COLUMNS = ["Missed- Severe", "Missed- Minor"]
ADDED_COLUMNS = ["Added- Hallucination", "Added- Not relevant"]
ERROR_COLUMNS = MISSED_COLUMNS + ADDED_COLUMNS
GROUPING_KEY = ["Section", "Field"]
EXCLUDED_SECTIONS = {"Gp Practice"}


@dataclass
class ErrorAggregation:
    """Pooled per-field counts and summary statistics across evaluated admissions."""

    field_counts: pd.DataFrame
    num_evaluations: int
    num_unique_hadm_ids: int
    deduplicated: bool
    total_errors_list: list[float]
    num_p_lt_fp: int
    num_field_evals: int


def load_eval_dfs(annotated_dir: Path = ANNOTATED_DIR) -> list[pd.DataFrame]:
    """Load and preprocess annotated evaluation spreadsheets."""
    eval_dfs = []
    for annotator_dir in sorted(annotated_dir.iterdir()):
        if not annotator_dir.is_dir():
            continue
        for hadm_dir in sorted(annotator_dir.iterdir()):
            excel_path = hadm_dir / f"discharge_summary_{hadm_dir.stem}.xlsx"
            if not hadm_dir.is_dir() or not excel_path.exists():
                continue

            df = pd.read_excel(excel_path, engine="openpyxl", header=1).dropna(how="all")

            # TODO: Remove when fixed in annotator
            mask = (df["Section"] == "Allergies And Adverse Reaction") & df[
                "Field"
            ].isnull()
            if mask.any():
                df.loc[mask, "Field"] = "Causative Agent"
                df.loc[mask, "Value"] = "No known drug allergies or adverse reactions"
                df.loc[-1, "Field"] = "Description Of Reaction"
                df.loc[-1, "Value"] = "No known drug allergies or adverse reactions"

            df["Section"] = df["Section"].ffill()
            df["Field"] = df["Field"].ffill()

            # Autopopulated fields are not generated by the LLM
            df = df.loc[df["Value"] != "Autopopulated"]
            df[ERROR_COLUMNS] = df[ERROR_COLUMNS].fillna(0)

            # Normalise numbered allergy fields for grouping
            for prefix in ("Causative Agent", "Description Of Reaction"):
                df["Field"] = df["Field"].str.replace(
                    rf"{prefix} [0-9]+", prefix, regex=True
                )

            df.hadm_id = hadm_dir.stem
            df.annotator = annotator_dir.stem
            eval_dfs.append(df)

    return eval_dfs


def _summarise_single_eval(eval_df: pd.DataFrame) -> pd.DataFrame:
    """Summarise error counts, generated element counts, and not-found flags per field."""
    filtered = eval_df[~eval_df["Section"].isin(EXCLUDED_SECTIONS)]
    grouped = filtered.groupby(GROUPING_KEY)

    counts = grouped[ERROR_COLUMNS].sum().astype(float)
    # Count list items or ". "-separated sentences for non-empty fields
    counts["Num Values"] = [
        float(
            sum(
                len(str(v).split(". "))
                for v in values
                if v != "Information not found in notes"
            )
        )
        for _, values in grouped["Value"]
    ]
    not_found = (
        filtered[filtered["Value"] == "Information not found in notes"]
        .groupby(GROUPING_KEY)["Value"]
        .count()
    )
    counts["Not Found"] = not_found.reindex(counts.index, fill_value=0).astype(float)
    return counts


def _build_metrics_table(
    counts: pd.DataFrame, num_evals: int, fields_per_row: pd.Series | int = 1
) -> pd.DataFrame:
    """Compute element statistics, Recall, Precision, and F1 from pooled counts."""
    tp = counts["True Positives"]
    fp = counts["False Positives"]
    fn = counts["False Negatives"]

    recall = (tp / (tp + fn)).fillna(0.0)
    precision = (tp / (tp + fp)).fillna(0.0)
    f1 = (2 * tp / (2 * tp + fp + fn)).fillna(0.0)

    return pd.DataFrame(
        {
            "Average Number of Elements": counts["Num Values"] / num_evals,
            "Proportion Not Found in Notes": counts["Not Found"]
            / (num_evals * fields_per_row),
            "Recall": recall,
            "Precision": precision,
            "F1": f1,
        },
        index=counts.index,
    )


def aggregate_field_counts(
    eval_dfs: list[pd.DataFrame], deduplicate: bool = True
) -> ErrorAggregation:
    """Aggregate per-field counts, optionally deduplicating double-annotated admissions.

    When ``deduplicate=True`` (N=53 -> N=49), evaluations sharing a ``hadm_id`` keep
    ``Num Values`` (P_hat) and ``Not Found`` once and average annotator error counts
    before summing across admissions. Pooled ``True Positives`` are ``max(0, P_hat - FP)``.
    """
    if not eval_dfs:
        raise ValueError("No evaluation dataframes were loaded.")

    per_eval = []
    num_p_lt_fp = 0
    num_field_evals = 0

    for df in eval_dfs:
        counts = _summarise_single_eval(df)
        num_p_lt_fp += int((counts["Num Values"] < counts[ADDED_COLUMNS].sum(axis=1)).sum())
        num_field_evals += len(counts)
        counts["hadm_id"] = df.hadm_id
        per_eval.append(counts)

    combined = pd.concat(per_eval)
    combined.index.names = GROUPING_KEY

    if deduplicate:
        by_hadm = combined.groupby(["hadm_id", *GROUPING_KEY], sort=False)
        deduped = pd.concat(
            [by_hadm[ERROR_COLUMNS].mean(), by_hadm[["Num Values", "Not Found"]].first()],
            axis=1,
        )
        num_evals = int(deduped.index.get_level_values("hadm_id").nunique())
        total_errors_list = [
            float(v)
            for v in deduped[ERROR_COLUMNS].sum(axis=1).groupby(level="hadm_id").sum()
        ]
        field_counts = deduped.groupby(GROUPING_KEY).sum()
    else:
        num_evals = len(eval_dfs)
        total_errors_list = [float(t[ERROR_COLUMNS].sum().sum()) for t in per_eval]
        field_counts = combined.drop(columns=["hadm_id"]).groupby(GROUPING_KEY).sum()

    field_counts["False Positives"] = field_counts[ADDED_COLUMNS].sum(axis=1)
    field_counts["False Negatives"] = field_counts[MISSED_COLUMNS].sum(axis=1)
    field_counts["True Positives"] = (
        field_counts["Num Values"] - field_counts["False Positives"]
    ).clip(lower=0.0)

    return ErrorAggregation(
        field_counts=field_counts,
        num_evaluations=num_evals,
        num_unique_hadm_ids=len({df.hadm_id for df in eval_dfs}),
        deduplicated=deduplicate,
        total_errors_list=total_errors_list,
        num_p_lt_fp=num_p_lt_fp,
        num_field_evals=num_field_evals,
    )


def compute_per_field_metrics(
    field_counts: pd.DataFrame, num_evals: int
) -> pd.DataFrame:
    """Compute per-field element statistics, Recall, Precision, and F1."""
    return _build_metrics_table(field_counts, num_evals)


def compute_per_section_metrics(
    field_counts: pd.DataFrame, num_evals: int
) -> pd.DataFrame:
    """Compute within-section micro-averaged Recall, Precision, and F1."""
    section_counts = field_counts.groupby(level="Section").sum()
    fields_per_section = field_counts.groupby(level="Section").size()
    return _build_metrics_table(section_counts, num_evals, fields_per_section)


def compute_overall_metrics(
    field_counts: pd.DataFrame,
    per_field_metrics: pd.DataFrame,
    per_section_metrics: pd.DataFrame,
    num_evals: int,
) -> pd.DataFrame:
    """Compute Field-Macro (N=17), Element-Micro, and Section-Macro (N=8) averages."""
    num_fields = len(per_field_metrics)
    num_sections = len(per_section_metrics)

    totals = field_counts.sum().to_frame().T
    element_micro = _build_metrics_table(totals, num_evals, num_fields).iloc[0]

    overall_df = pd.DataFrame(
        {
            f"Field-Macro Average (N={num_fields})": per_field_metrics.mean(axis=0),
            "Element-Micro Average": element_micro,
            f"Section-Macro Average (N={num_sections})": per_section_metrics.mean(axis=0),
        }
    ).T
    overall_df.index.name = "Averaging"
    return overall_df


def append_overall_rows(
    table: pd.DataFrame, overall_metrics: pd.DataFrame
) -> pd.DataFrame:
    """Append Field-Macro and Element-Micro summary rows to a field or section table."""
    keep = [
        idx
        for idx in overall_metrics.index
        if idx.startswith("Field-Macro Average") or idx == "Element-Micro Average"
    ]
    summary = overall_metrics.loc[keep, table.columns].copy()
    if table.index.nlevels == 2:
        summary.index = pd.MultiIndex.from_tuples(
            [(label, "") for label in summary.index], names=table.index.names
        )
    else:
        summary.index.name = table.index.name
    return pd.concat([table, summary])


def compute_error_proportions(field_counts: pd.DataFrame) -> pd.DataFrame:
    """Compute total counts and percentage share for each error category."""
    totals = field_counts[ERROR_COLUMNS].sum()
    df = pd.DataFrame({"Count": totals, "Percentage (%)": totals / totals.sum() * 100.0})
    df.index.name = "Error Category"
    return df


def compute_fn_fp_agreement(
    eval_dfs: list[pd.DataFrame], grouping_key: list[str] = GROUPING_KEY
) -> float | None:
    """Compute exact agreement on (FN, FP) counts for double-annotated summaries."""
    by_hadm: dict[str, list[pd.DataFrame]] = defaultdict(list)
    for df in eval_dfs:
        by_hadm[df.hadm_id].append(df)

    matches: list[bool] = []
    for dfs in by_hadm.values():
        if len(dfs) != 2:
            continue
        g1 = dfs[0].groupby(grouping_key)[ERROR_COLUMNS].sum().astype(int)
        g2 = dfs[1].groupby(grouping_key)[ERROR_COLUMNS].sum().astype(int)
        fn_fp_1 = zip(g1[MISSED_COLUMNS].sum(axis=1), g1[ADDED_COLUMNS].sum(axis=1))
        fn_fp_2 = zip(g2[MISSED_COLUMNS].sum(axis=1), g2[ADDED_COLUMNS].sum(axis=1))
        matches.extend(a == b for a, b in zip(fn_fp_1, fn_fp_2))

    return sum(matches) / len(matches) if matches else None


def save_metrics_outputs(
    per_field_metrics: pd.DataFrame,
    per_section_metrics: pd.DataFrame,
    overall_metrics: pd.DataFrame,
    error_proportions: pd.DataFrame,
    summary_stats: dict[str, object],
    output_dir: Path = METRICS_OUTPUT_DIR,
) -> list[Path]:
    """Write formatted metrics tables and summary JSON to the output directory."""
    output_dir.mkdir(parents=True, exist_ok=True)

    tables = [
        ("per_field_metrics", append_overall_rows(per_field_metrics, overall_metrics)),
        ("per_section_metrics", append_overall_rows(per_section_metrics, overall_metrics)),
        ("overall_metrics", overall_metrics),
        ("error_proportions", error_proportions),
    ]

    written_paths: list[Path] = []
    for name, df in tables:
        for ext, text in (
            ("md", df.to_markdown(floatfmt=".2f")),
            ("tex", df.to_latex(float_format="%.2f")),
        ):
            path = output_dir / f"{name}.{ext}"
            path.write_text(text)
            written_paths.append(path)

    for name, df in (
        ("per_field_metrics", per_field_metrics),
        ("per_section_metrics", per_section_metrics),
    ):
        csv_path = output_dir / f"{name}.csv"
        csv_path.write_text(df.to_csv(float_format="%.2f"))
        written_paths.append(csv_path)

    json_path = output_dir / "summary.json"
    json_path.write_text(json.dumps(summary_stats, indent=2) + "\n")
    written_paths.append(json_path)
    return written_paths


def _compute_all_tables(
    eval_dfs: list[pd.DataFrame], deduplicate: bool
) -> tuple[ErrorAggregation, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Run aggregation and compute field, section, and overall metric tables."""
    agg = aggregate_field_counts(eval_dfs, deduplicate=deduplicate)
    per_field = compute_per_field_metrics(agg.field_counts, agg.num_evaluations)
    per_section = compute_per_section_metrics(agg.field_counts, agg.num_evaluations)
    overall = compute_overall_metrics(
        agg.field_counts, per_field, per_section, agg.num_evaluations
    )
    return agg, per_field, per_section, overall


def main() -> None:
    """Run the deduplicated (N=49) metrics pipeline and export results."""
    pd.options.display.float_format = "{:,.2f}".format

    eval_dfs = load_eval_dfs()
    agg, per_field, per_section, overall = _compute_all_tables(eval_dfs, deduplicate=True)
    _, _, _, pooled_overall = _compute_all_tables(eval_dfs, deduplicate=False)

    error_proportions = compute_error_proportions(agg.field_counts)
    median_errors = float(np.median(agg.total_errors_list))
    fn_fp_agreement = compute_fn_fp_agreement(eval_dfs)

    num_fields, num_sections = len(per_field), len(per_section)
    field_macro_key = f"Field-Macro Average (N={num_fields})"
    section_macro_key = f"Section-Macro Average (N={num_sections})"

    summary_stats: dict[str, object] = {
        "deduplicated": agg.deduplicated,
        "num_raw_evaluations": len(eval_dfs),
        "num_evaluated_admissions": agg.num_evaluations,
        "num_unique_hadm_ids": agg.num_unique_hadm_ids,
        "num_fields": num_fields,
        "num_sections": num_sections,
        "num_p_lt_fp": agg.num_p_lt_fp,
        "num_field_evals": agg.num_field_evals,
        "median_errors_per_summary": median_errors,
        "fn_fp_agreement": fn_fp_agreement,
        "field_macro_average": overall.loc[field_macro_key].to_dict(),
        "element_micro_average": overall.loc["Element-Micro Average"].to_dict(),
        "section_macro_average": overall.loc[section_macro_key].to_dict(),
        "pooled_n53_comparison": {
            "field_macro_average": pooled_overall.loc[field_macro_key].to_dict(),
            "element_micro_average": pooled_overall.loc["Element-Micro Average"].to_dict(),
        },
        "error_proportions": error_proportions.to_dict(orient="index"),
    }

    written_paths = save_metrics_outputs(
        per_field, per_section, overall, error_proportions, summary_stats
    )

    print(
        f"Loaded {len(eval_dfs)} raw evaluations -> "
        f"{agg.num_evaluations} unique admissions (deduplicated={agg.deduplicated})"
    )
    print(f"Number of times P < FP: {agg.num_p_lt_fp}/{agg.num_field_evals}")
    print(f"Median errors per summary: {median_errors:.2f}")
    if fn_fp_agreement is not None:
        print(f"FN/FP exact agreement (paired): {fn_fp_agreement:.2f}")
    print("\nPer-Section Metrics (Table 3.4):")
    print(append_overall_rows(per_section, overall))
    print("\nOverall Metrics:")
    print(overall)
    print("\nError Proportions:")
    print(error_proportions)
    print("\nOutputs written to:")
    for path in written_paths:
        print(f" - {path}")


if __name__ == "__main__":
    main()
