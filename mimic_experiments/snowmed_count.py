import pandas as pd
from pathlib import Path
from medcat.cat import CAT

OUTPUT_DIR = Path.cwd() / "outputs"
ANNOTATED_DIR = OUTPUT_DIR / "annotators_eval"

ERROR_COLUMNS = [
    "Missed- Severe",
    "Missed- Minor",
    "Added- Hallucination",
    "Added- Not relevant",
]

def load_clinical_summaries()->pd.DataFrame:
    """
    Loads the clinical summaries from the annotated outputs
    """
    eval_dfs = []
    for annotator_dir in ANNOTATED_DIR.iterdir():
        if not annotator_dir.is_dir():
            continue

        for hadm_id_dir in annotator_dir.iterdir():
            if not hadm_id_dir.is_dir():
                continue

            hadm_id = hadm_id_dir.stem
            df = pd.read_excel(
                (hadm_id_dir / f"discharge_summary_{hadm_id}.xlsx"),
                engine="openpyxl",
                header=1,
            )

            # Drop empty rows
            df = df.dropna(axis=0, how="all")

            # TODO: Remove when fixed in annotator
            mask = (df["Section"] == "Allergies And Adverse Reaction") & (
                df["Field"].isnull()
            )
            if mask.any():
                df.loc[mask, "Field"] = "Causative Agent"
                df.loc[mask, "Value"] = "No known drug allergies or adverse reactions"
                df.loc[-1, "Field"] = "Description Of Reaction"
                df.loc[-1, "Value"] = "No known drug allergies or adverse reactions"

            # Fill empty sections and fields with whatever is above
            df["Section"] = df["Section"].ffill()
            df["Field"] = df["Field"].ffill()
            # Autopopulated fields are not generated by LLM so we can drop them
            # from evaluation
            df = df.loc[df["Value"] != "Autopopulated"]

            # Empty cells are not errors so set to 0
            df[ERROR_COLUMNS] = df[ERROR_COLUMNS].fillna(0)

            # Help with grouping
            df["Field"] = df["Field"].str.replace(
                r"Causative Agent [0-9]+", "Causative Agent", regex=True
            )
            df["Field"] = df["Field"].str.replace(
                r"Description Of Reaction [0-9]+", "Description Of Reaction", regex=True
            )

            # Help with identification downstream
            df.hadm_id = hadm_id
            df.annotator = annotator_dir.stem
            eval_dfs.append(df)
    len(eval_dfs)


    clinical_summaries = pd.concat([eval_df[eval_df["Field"] == "Clinical Summary"] for eval_df in eval_dfs])
    clinical_summaries = clinical_summaries.drop_duplicates(subset=['Value'])
    return clinical_summaries    


if __name__ == "__main__":
    clinical_summaries = load_clinical_summaries()    
    cat = CAT.load_model_pack('models/v2_Snomed2025_MIMIC_IV_bbe806e192df009f.zip')

    clinical_summaries["Sentence Count"] = [
        len(text.split(". ")) for text in clinical_summaries["Value"]
    ]

    clinical_summaries["SNOMED Count"] = [
        len(set(entity["cui"] for entity in cat.get_entities(text).get("entities", {}).values()))
        for text in clinical_summaries["Value"]
    ]


    print(f"Average number of sentences per summary: {clinical_summaries["Sentence Count"].mean():.2f}")
    print(f"Average number of SNOMED concepts per summary: {clinical_summaries["SNOMED Count"].mean():.2f}")
