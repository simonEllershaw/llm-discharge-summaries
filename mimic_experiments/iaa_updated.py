from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

BASE_DIR = Path(__file__).resolve().parent
OUTPUT_DIR = BASE_DIR / "outputs"
ANNOTATED_DIR = OUTPUT_DIR / "annotators_eval"
IAA_OUTPUT_DIR = OUTPUT_DIR / "iaa"

ERROR_COLUMNS = [
    "Missed- Severe",
    "Missed- Minor",
    "Added- Hallucination",
    "Added- Not relevant",
]
GROUPING_KEY = ["Section", "Field"]


def load_eval_dfs() -> list[pd.DataFrame]:
    """Load and preprocess annotated evaluation spreadsheets."""
    eval_dfs = []
    for annotator_dir in ANNOTATED_DIR.iterdir():
        if not annotator_dir.is_dir():
            continue

        for hadm_id_dir in annotator_dir.iterdir():
            if not hadm_id_dir.is_dir():
                continue

            hadm_id = hadm_id_dir.stem
            excel_path = hadm_id_dir / f"discharge_summary_{hadm_id}.xlsx"
            if not excel_path.exists():
                continue

            df = pd.read_excel(excel_path, engine="openpyxl", header=1)

            # Drop empty rows
            df = df.dropna(axis=0, how="all")

            # Fix missing allergy fields
            mask = (df["Section"] == "Allergies And Adverse Reaction") & (
                df["Field"].isnull()
            )
            if mask.any():
                df.loc[mask, "Field"] = "Causative Agent"
                df.loc[mask, "Value"] = "No known drug allergies or adverse reactions"
                df.loc[-1, "Field"] = "Description Of Reaction"
                df.loc[-1, "Value"] = "No known drug allergies or adverse reactions"

            # Fill empty sections and fields with whatever is above
            df["Section"] = df["Section"].ffill()
            df["Field"] = df["Field"].ffill()

            # Autopopulated fields are not generated by LLM so drop from evaluation
            df = df.loc[df["Value"] != "Autopopulated"]

            # Empty cells are not errors so set to 0
            df[ERROR_COLUMNS] = df[ERROR_COLUMNS].fillna(0)

            # Normalize numbered allergy fields for grouping
            df["Field"] = df["Field"].str.replace(
                r"Causative Agent [0-9]+", "Causative Agent", regex=True
            )
            df["Field"] = df["Field"].str.replace(
                r"Description Of Reaction [0-9]+", "Description Of Reaction", regex=True
            )

            df.hadm_id = hadm_id
            df.annotator = annotator_dir.stem
            eval_dfs.append(df)

    return eval_dfs


def get_paired_field_counts(eval_dfs: list[pd.DataFrame]) -> np.ndarray:
    """Extract paired 4D error count vectors per field for double-annotated summaries."""
    hadm_id_to_annotator_dfs = defaultdict(list)
    for eval_df in eval_dfs:
        hadm_id_to_annotator_dfs[eval_df.hadm_id].append(eval_df)

    paired_hadm_id_to_annotator_dfs = {
        hadm_id: dfs
        for hadm_id, dfs in hadm_id_to_annotator_dfs.items()
        if len(dfs) == 2
    }

    multi_annotated_fields: list[tuple[tuple, tuple]] = []
    for annotator_dfs in paired_hadm_id_to_annotator_dfs.values():
        annotator_1_fields = (
            annotator_dfs[0]
            .groupby(GROUPING_KEY)
            .sum()[ERROR_COLUMNS]
            .values.astype(int)
            .tolist()
        )
        annotator_2_fields = (
            annotator_dfs[1]
            .groupby(GROUPING_KEY)
            .sum()[ERROR_COLUMNS]
            .values.astype(int)
            .tolist()
        )

        multi_annotated_fields.extend(
            [
                (tuple(annotator_1_field), tuple(annotator_2_field))
                for annotator_1_field, annotator_2_field in zip(
                    annotator_1_fields, annotator_2_fields
                )
            ]
        )

    return np.array(multi_annotated_fields)


def krippendorff_alpha_interval(y_0: np.ndarray, y_1: np.ndarray) -> float:
    """Calculate Krippendorff's alpha (interval metric) for two complete raters."""
    y_0 = np.asarray(y_0, dtype=float)
    y_1 = np.asarray(y_1, dtype=float)
    observed_disagreement = np.mean((y_0 - y_1) ** 2)
    expected_disagreement = 2.0 * np.var(np.concatenate([y_0, y_1]), ddof=1)
    if expected_disagreement == 0:
        return 1.0
    return float(1.0 - (observed_disagreement / expected_disagreement))


def build_row_metrics(y_0: np.ndarray, y_1: np.ndarray) -> dict[str, str | float]:
    """Compute summary statistics and agreement metrics for a pair of count arrays."""
    total_units = len(y_0)
    non_zero_units = int(np.sum((y_0 > 0) | (y_1 > 0)))
    exact_agreement_pct = float(np.mean(y_0 == y_1) * 100.0)
    alpha = krippendorff_alpha_interval(y_0, y_1)
    return {
        "Non-Zero Fields": f"{non_zero_units} / {total_units}",
        "Exact Agreement (%)": exact_agreement_pct,
        "Krippendorff's Alpha": alpha,
    }


def compute_iaa_metrics(paired_counts: np.ndarray) -> pd.DataFrame:
    """Compute thesis table of inter-annotator agreement per error type and overall."""
    anno_0_counts = paired_counts[:, 0, :]
    anno_1_counts = paired_counts[:, 1, :]

    rows = {}
    for idx, col in enumerate(ERROR_COLUMNS):
        rows[col] = build_row_metrics(anno_0_counts[:, idx], anno_1_counts[:, idx])

    rows["Overall (Pooled)"] = build_row_metrics(
        # Flatten out counts
        anno_0_counts.ravel(), anno_1_counts.ravel()
    )

    df = pd.DataFrame.from_dict(rows, orient="index")
    df.index.name = "Error Category"
    return df


if __name__ == "__main__":
    pd.options.display.float_format = "{:,.3f}".format
    eval_dfs = load_eval_dfs()
    paired_counts = get_paired_field_counts(eval_dfs)
    print(f"Loaded {len(eval_dfs)} evaluations ({len(paired_counts)} paired fields)\n")

    iaa_df = compute_iaa_metrics(paired_counts)
    print("Inter-Annotator Agreement Table:")
    print(iaa_df)

    IAA_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    (IAA_OUTPUT_DIR / "table.md").write_text(iaa_df.to_markdown(floatfmt=".3f"))
    (IAA_OUTPUT_DIR / "table.tex").write_text(iaa_df.to_latex(float_format="%.3f"))

    print(
        f"\nOutputs written to:\n - {IAA_OUTPUT_DIR / 'table.md'}\n - {IAA_OUTPUT_DIR / 'table.tex'}"
    )
